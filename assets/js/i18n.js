let current = "pt";

export function getLang() {
  return current;
}

export function setLang(lang) {
  current = dict[lang] ? lang : "pt";
  try {
    localStorage.setItem("jsa-lang", current);
  } catch {
    /* ignore */
  }
  return current;
}

export function initLang() {
  try {
    const saved = localStorage.getItem("jsa-lang");
    if (saved && dict[saved]) current = saved;
    else if (navigator.language?.toLowerCase().startsWith("en")) current = "en";
  } catch {
    /* ignore */
  }
  return current;
}

export function t(key) {
  return dict[current][key] ?? dict.en[key] ?? key;
}

export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key));
  });
}
